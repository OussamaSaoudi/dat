  test("ic_015_merge") {
    sql("""CREATE TABLE tbl (
      id LONG GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 2),
      value INT
    ) USING delta TBLPROPERTIES ('delta.enableDeletionVectors' = 'true')""")
    sql("INSERT INTO tbl (value) VALUES (10),(20),(30)")
    sql("CREATE TABLE src (value INT) USING delta")
    sql("INSERT INTO src VALUES (20),(40)")
    sql("""MERGE INTO tbl t USING src s ON t.value = s.value
      WHEN MATCHED THEN UPDATE SET value = s.value * 10
      WHEN NOT MATCHED THEN INSERT (value) VALUES (s.value)""")
    val t = registerTable("tbl")
    read(t)
    read(t, version = 1)
    val N = 2L
    for (v <- 0L to N) snapshot(t, version = v)
  }

