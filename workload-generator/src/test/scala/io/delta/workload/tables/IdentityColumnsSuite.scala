  test("ic_007_replace_resets_watermark") {
    sql("""CREATE TABLE tbl (
      id LONG GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 1),
      value INT
    ) USING delta TBLPROPERTIES ('delta.enableDeletionVectors' = 'true')""")
