    sql("INSERT INTO tbl (value) VALUES (2)")
    sql("""CREATE OR REPLACE TABLE tbl (
      id LONG GENERATED ALWAYS AS IDENTITY (START WITH 5000 INCREMENT BY 1),
      value STRING
