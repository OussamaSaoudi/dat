  // -- ic_015_merge: identity after MERGE --
  test("ic_015_merge", "Identity columns after MERGE", "identityColumns") { w =>
    w.sql("""CREATE TABLE tbl (
      id LONG GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 2),
      value INT
    ) USING delta TBLPROPERTIES ('delta.enableDeletionVectors' = 'true')""")
    w.sql("INSERT INTO tbl (value) VALUES (10),(20),(30)")
    w.sql("CREATE TABLE src (value INT) USING delta")
    w.sql("INSERT INTO src VALUES (20),(40)")
    w.sql("""MERGE INTO tbl t USING src s ON t.value = s.value
      WHEN MATCHED THEN UPDATE SET value = s.value * 10
      WHEN NOT MATCHED THEN INSERT (value) VALUES (s.value)""")
    val t = w.table("tbl")
    w.read(t)
    w.read(t, version = 1)
    w.snapshotHistory(t)
  }

