new WorkloadSuite("identity_columns") {

  // -- ic_001_various_config: identity with start=1000, step=100 --
  test("ic_001_various_config", "Read identity with various start/step configurations", "identityColumns") { w =>
    w.sql("""CREATE TABLE tbl (
      id LONG GENERATED ALWAYS AS IDENTITY (START WITH 1000 INCREMENT BY 100),
      value INT
    ) USING delta TBLPROPERTIES ('delta.enableDeletionVectors' = 'true')""")
    w.sql("INSERT INTO tbl (value) VALUES (10)")
    w.sql("INSERT INTO tbl (value) VALUES (20)")
    w.sql("INSERT INTO tbl (value) VALUES (30)")
    val t = w.table("tbl")
    w.read(t)
    w.read(t, predicate = "id >= 1000 AND id <= 1200")
    w.read(t, columns = Seq("id"))
    w.snapshot(t)
  }

